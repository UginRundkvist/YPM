SET DEFINE ON
SET VERIFY OFF
ACCEPT owner_password CHAR PROMPT 'Пароль ZERD: ' HIDE


CREATE USER Zerd IDENTIFIED BY "&owner_password"
    DEFAULT TABLESPACE users
    QUOTA 20M ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW TO Zerd;

UNDEFINE owner_password

