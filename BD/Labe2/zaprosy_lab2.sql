-- Лабораторная №2. Запросы к базе ED_SALES.
-- Проверено на данных выгрузки: справа от каждого пункта — сколько строк должно вернуться.

-- ============================================================
-- Пункт 1. Все разнообразные фамилии.                [21 строка]
-- DISTINCT нужен: СМИТ и ФОРД встречаются по два раза.
select distinct Фамилия
from ed_sales."СОТРУДНИКИ";


-- ============================================================
-- Пункт 2. Сотрудники, их отдел и должность.         [23 строки]
select Фамилия, Ном_Отдела, Должность
from ed_sales."СОТРУДНИКИ";


-- ============================================================
-- Пункт 3. То же, но только по отделению 20.          [7 строк]
-- ВНИМАНИЕ: у тебя было 30, в задании 20.
select Фамилия, Ном_Отдела, Должность
from ed_sales."СОТРУДНИКИ"
where Ном_Отдела = 20;


-- ============================================================
-- Пункт 4. Месячная и годовая зарплата продавцов и аналитиков. [8 строк]
-- ВНИМАНИЕ: литералы в кавычках регистрозависимы.
-- 'Продавец' не равно 'ПРОДАВЕЦ' — с маленькой буквы вернётся 0 строк.
select Фамилия,
       оклад        AS "месячная",
       оклад * 12   AS "годовая"
from ed_sales."СОТРУДНИКИ"
where должность IN ('ПРОДАВЕЦ', 'АНАЛИТИК');


-- ============================================================
-- Пункт 5. Список персонала по дате приёма и должности. [23 строки]
select *
from ed_sales."СОТРУДНИКИ"
order by дата_приема asc, должность;


-- ============================================================
-- Пункт 6. Премия — 10% надбавки, округлить до целого.  [8 строк]
-- ВНИМАНИЕ: было "надбавка is not null" — в этих данных надбавка
-- никогда не NULL, вместо пустоты стоит 0, поэтому фильтр
-- пропускал все 23 строки с премией 0. Нужно "> 0".
select Фамилия,
       надбавка,
       ROUND(надбавка * 0.10) AS премия
from ed_sales."СОТРУДНИКИ"
where надбавка > 0;


-- ============================================================
-- Пункт 7. Названия отделов в трёх регистрах.           [4 строки]
-- INITCAP сам приводит остаток слова к нижнему регистру.
select НАИМ_ОТДЕЛА                 AS "как в базе",
       UPPER(НАИМ_ОТДЕЛА)          AS "верхний",
       LOWER(НАИМ_ОТДЕЛА)          AS "нижний",
       INITCAP(НАИМ_ОТДЕЛА)        AS "с большой буквы"
from ed_sales."ОТДЕЛЫ";


-- ============================================================
-- Пункт 8. Средняя зарплата по каждому отделу.          [4 строки]
-- Ожидаемо: 10 -> 2916.67, 20 -> 2232.14, 30 -> 1568.17, 40 -> 2942.86
select Ном_Отдела,
       ROUND(AVG(оклад), 2) AS "средний оклад"
from ed_sales."СОТРУДНИКИ"
group by Ном_Отдела
order by Ном_Отдела;


-- ============================================================
-- Пункт 9. Отделы, где менее четырёх человек.           [1 строка]
-- Условие на результат группировки — это HAVING, не WHERE.
-- WHERE отсекает строки ДО группировки, HAVING — готовые группы.
-- Ожидаемо: отдел 10, 3 человека.
select Ном_Отдела,
       COUNT(*) AS "сотрудников"
from ed_sales."СОТРУДНИКИ"
group by Ном_Отдела
having COUNT(*) < 4;


-- ============================================================
-- Пункт 10. Максимальная зарплата с надбавкой по отделам. [4 строки]
-- NVL меняет NULL на 0: без него сумма с пустой надбавкой стала бы NULL
-- и сотрудник выпал бы из сравнения.
-- Ожидаемо: 10 -> 5000, 20 -> 3150, 30 -> 2850, 40 -> 4000
select Ном_Отдела,
       MAX(оклад + NVL(надбавка, 0)) AS "макс. доход"
from ed_sales."СОТРУДНИКИ"
group by Ном_Отдела
order by Ном_Отдела;


-- ============================================================
-- Пункт 11. Сумма зарплат операционистов и кассиров.    [1 строка]
-- Ожидаемо: 15750
select SUM(оклад) AS "расходная сумма"
from ed_sales."СОТРУДНИКИ"
where должность IN ('ОПЕРАЦИОНИСТ', 'КАССИР');


-- ============================================================
-- Пункт 12. Сколько различных профессий в отделах 10 и 40. [1 строка]
-- DISTINCT внутри COUNT: иначе посчитались бы все 10 человек,
-- а не 5 разных должностей.
-- Ожидаемо: 5 (МЕНЕДЖЕР, ПРЕЗИДЕНТ, КЛЕРК, ОПЕРАЦИОНИСТ, КАССИР)
select COUNT(DISTINCT должность) AS "разных профессий"
from ed_sales."СОТРУДНИКИ"
where Ном_Отдела IN (10, 40);


-- ============================================================
-- Пункт 13. Иерархия: подчинённые Мартинса, кроме Харда.   [0 строк!]
-- START WITH задаёт корень обхода, CONNECT BY PRIOR — направление:
-- "ном_сотр предыдущего уровня = ном_нлнк текущего" значит идём вниз,
-- от начальника к подчинённым.
-- Условие "<> 'ХАРД'" стоит в CONNECT BY, а не в WHERE: так отсекается
-- вся ветка Харда вместе с его подчинёнными, а не только он сам.
-- Внешний WHERE убирает самого Мартинса из выдачи.
--
-- ВАЖНО: на этих данных вернёт 0 строк — у Мартинса нет подчинённых,
-- он сам ОПЕРАЦИОНИСТ в отделе 40 и подчиняется Турсу. См. запрос-диагностику ниже.
select Фамилия, Должность, LEVEL AS "уровень"
from ed_sales."СОТРУДНИКИ"
where Фамилия <> 'МАРТИНС'
start with Фамилия = 'МАРТИНС'
connect by prior ном_сотр = ном_нлнк
       and Фамилия <> 'ХАРД';

-- Диагностика к пункту 13: кто кому подчиняется в отделе 40.
-- Видно, что начальник там Турс, а Хард и Мартинс — равные ему подчинённые.
select e.ном_сотр, e.Фамилия, e.Должность, e.ном_нлнк, b.Фамилия AS начальник
from ed_sales."СОТРУДНИКИ" e
     left join ed_sales."СОТРУДНИКИ" b on b.ном_сотр = e.ном_нлнк
where e.Ном_Отдела = 40
order by e.ном_сотр;

-- Тот же иерархический запрос от Турса — даёт осмысленные 5 строк:
-- ДУЛЛИТ, МАКЛАЙ, МАРТИНС, ТОМАСОН, ХАЙК (Хард отсечён).
select Фамилия, Должность, LEVEL AS "уровень"
from ed_sales."СОТРУДНИКИ"
where Фамилия <> 'ТУРС'
start with Фамилия = 'ТУРС'
connect by prior ном_сотр = ном_нлнк
       and Фамилия <> 'ХАРД';


-- ============================================================
-- Пункт 14. Клиенты с кредитом от 3500 и выше.          [8 строк]
-- "от 3500 и выше" — включительно, значит >=, а не >.
select ном_кл, Имя, Кредит
from ed_sales."КЛИЕНТЫ"
where Кредит >= 3500
order by Кредит desc;


-- ============================================================
-- Пункт 15. Футбольные товары: описание, прайс и мин. цена. [2 строки]
-- Соединение по ном_прод. "Действующий прайслист" — та цена,
-- у которой не заполнена дата окончания.
-- Ожидаемо: КРОССОВКИ 99.9/78 и МЯЧ 300.75/240.6
select p.ном_прод,
       p.Наименование,
       p.Описание,
       c.розн_цена  AS "действующая цена",
       c.мин_цена   AS "минимальная"
from ed_sales."ПРОДУКТЫ" p
     join ed_sales."ЦЕНЫ" c on c.ном_прод = p.ном_прод
where p.Описание = 'ФУТБОЛ'
  and c.дата_окон is null;


-- ============================================================
-- Пункт 16. Кто к 1998 году проработал менее года.      [1 строка]
-- MONTHS_BETWEEN(поздняя, ранняя) даёт стаж в месяцах на 01.01.1998.
-- Нижняя граница ">= 0" отсекает тех, кого на эту дату ещё не приняли:
-- Форд (12.12.1998) и Смит (17.12.1998) приняты уже ПОСЛЕ 1998 года,
-- без этого условия они бы попали в выдачу с отрицательным стажем.
-- Ожидаемо: СМИТ, ПРОДАВЕЦ, 11.11.1997
select Фамилия,
       Должность,
       дата_приема,
       ROUND(MONTHS_BETWEEN(DATE '1998-01-01', дата_приема), 1) AS "стаж, мес."
from ed_sales."СОТРУДНИКИ"
where MONTHS_BETWEEN(DATE '1998-01-01', дата_приема) >= 0
  and MONTHS_BETWEEN(DATE '1998-01-01', дата_приема) < 12;
