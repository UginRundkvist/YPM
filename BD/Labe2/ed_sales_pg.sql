CREATE TABLE ЗАКАЗЫ (
  НОМ_ЗАК          numeric,
  НОМ_КЛ           numeric,
  ДАТА_ЗАК         date,
  ДАТА_ДОСТ        date,
  НОМ_СЧ           numeric,
  КОММЕНТАРИЙ      varchar(50),
  CONSTRAINT PK_ЗАКАЗЫ PRIMARY KEY (НОМ_ЗАК)
);
CREATE TABLE ПОЗИЦИИ (
  НОМ_ЗАК          numeric,
  НОМ_ПОЗ          numeric,
  НОМ_ПРОД         numeric,
  ЦЕНА_ПОКУП       numeric,
  КОЛ_ВО           numeric,
  CONSTRAINT PK_ПОЗИЦИИ PRIMARY KEY (НОМ_ЗАК, НОМ_ПОЗ)
);
CREATE TABLE ЦЕНЫ (
  НОМ_ПРОД         numeric NOT NULL,
  РОЗН_ЦЕНА        numeric,
  МИН_ЦЕНА         numeric,
  ДАТА_Н           date NOT NULL,
  ДАТА_ОКОН        date
);

