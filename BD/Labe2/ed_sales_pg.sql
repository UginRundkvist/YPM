CREATE TABLE КЛИЕНТЫ (
  НОМ_КЛ           numeric,
  ИМЯ              varchar(50),
  МЕСТО            varchar(50),
  УЛИЦА            varchar(50),
  КРЕДИТ           numeric,
  CONSTRAINT PK_КЛИЕНТЫ PRIMARY KEY (НОМ_КЛ)
);
CREATE TABLE ПРОДУКТЫ (
  НОМ_ПРОД         numeric,
  НАИМЕНОВАНИЕ     varchar(50),
  ОПИСАНИЕ         varchar(50),
  CONSTRAINT PK_ПРОДУКТЫ PRIMARY KEY (НОМ_ПРОД)
);
CREATE TABLE СОТРУДНИКИ (
  НОМ_СОТР         numeric,
  ФАМИЛИЯ          varchar(20),
  ДОЛЖНОСТЬ        varchar(50),
  НОМ_НЛНК         numeric,
